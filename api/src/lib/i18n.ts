const MESSAGES: Record<Locale, Messages> = { pt, en, es, fr }

export type Params = Record<string, string | number>

export function translate(locale: Locale, key: MessageKey, params: Params = {}) {
  return MESSAGES[locale][key].replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
}

export const t = (c: Context<AppEnv>, key: MessageKey, params?: Params) => translate(c.get('locale') ?? BASE_LOCALE, key, params)

export const fail = (c: Context<AppEnv>, status: ContentfulStatusCode, key: MessageKey, params?: Params) =>
  c.json({ error: t(c, key, params), code: key }, status)
