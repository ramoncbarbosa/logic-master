export const LOCALES = ['pt', 'en', 'es', 'fr'] as const
export type Locale = (typeof LOCALES)[number]
export const BASE_LOCALE: Locale = 'pt'
export const TRANSLATABLE_LOCALES = LOCALES.filter((l) => l !== BASE_LOCALE)

export const isLocale = (v: unknown): v is Locale => typeof v === 'string' && (LOCALES as readonly string[]).includes(v)

export function resolveLocale(header: string | null | undefined): Locale {
  if (!header) return BASE_LOCALE
  const ranked = header
    .split(',')
    .map((part) => {
      const [tag, q] = part.trim().split(';q=')
      return { lang: tag.toLowerCase().slice(0, 2), q: q ? Number(q) : 1 }
    })
    .sort((a, b) => b.q - a.q)
  return ranked.map((r) => r.lang).find(isLocale) ?? BASE_LOCALE
}

